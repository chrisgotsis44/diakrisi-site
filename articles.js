/* Βοηθητικά κοινά και για τις δύο σελίδες */
window.DIAKRISI_FMT_DATE = function (iso) {
  var m = ['Ιαν', 'Φεβ', 'Μαρ', 'Απρ', 'Μαΐ', 'Ιουν', 'Ιουλ', 'Αυγ', 'Σεπ', 'Οκτ', 'Νοε', 'Δεκ'];
  var p = iso.split('-');
  return parseInt(p[2], 10) + ' ' + m[parseInt(p[1], 10) - 1] + ' ' + p[0];
};

